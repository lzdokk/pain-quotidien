/** Photo du jour accordée aux thèmes trouvés (sinon tournante). */
export function photoOfDay(date: string, themeIds: string[]): Photo {
  const [y, m, d] = date.split('-').map(Number);
  const n = Math.floor(Date.UTC(y, m - 1, d) / 86400000);
  const pool = themeIds.length ? PHOTOS.filter(p => p.themes.some(t => themeIds.includes(t))) : PHOTOS;
  const list = pool.length ? pool : PHOTOS;
  return list[(n * 53) % list.length];
}
